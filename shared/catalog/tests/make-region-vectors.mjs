// Writes region-vectors.json from the TypeScript region map (game/reaches/regions.ts), for backend/regions.py
// to match. Run from frontend/ when the map changes on purpose:
//   node --experimental-strip-types --import ./tests/register.mjs ../shared/catalog/tests/make-region-vectors.mjs
import { writeFileSync } from "node:fs";
const { regionWeights, warp, latticeHash } = await import("../../../frontend/src/game/reaches/regions.ts");

const points = [];
// The centres, the hub's rim, borders, the edge, and a spread of places on a seeded walk
for (const [x, z] of [[0, 0], [0, -3800], [3740, -660], [1220, -3350], [0, -900], [6000, 0], [-6100, 40], [2190, 2600]]) points.push([x, z]);
let s = 7;
const next = () => (s = (Math.imul(s, 1103515245) + 12345) >>> 0) / 4294967296;
for (let i = 0; i < 60; i++) points.push([Math.round((next() - 0.5) * 13000 * 100) / 100, Math.round((next() - 0.5) * 13000 * 100) / 100]);
const cases = points.map(([x, z]) => ({ x, z, warp: warp(x, z), ...regionWeights(x, z) }));
const hashes = [[0, 0, 0], [-1, 5, 4060], [123456, -654321, 7], [-2147483648, 2147483647, 1]].map(([ix, iz, stream]) => ({ ix, iz, stream, value: latticeHash(ix, iz, stream) }));
writeFileSync(new URL("./region-vectors.json", import.meta.url), JSON.stringify({
  note: "Generated by make-region-vectors.mjs from frontend/src/game/reaches/regions.ts; backend/regions.py must give exactly these.",
  hashes, cases,
}, null, 1) + "\n");
console.log(`region-vectors.json: ${cases.length} points`);
