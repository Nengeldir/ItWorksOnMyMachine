// Generates frontend/src/catalog.gen.ts from the catalog's JSON Schemas (one
// TypeScript type per schema definition) and its data (a union of every id per
// file), so the frontend can't drift from the files it reads.
//
//   node shared/catalog/types.mjs           writes the file
//   node shared/catalog/types.mjs --check   exits 1 if the file is stale
//
// frontend's `npm run catalog` runs it (and `npm run build` runs that);
// frontend/tests/catalog.test.mjs fails when the committed file is stale.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG_DIR, FILES, LISTS, loadFiles, loadSchemas } from "./check.mjs";

export const OUTPUT = join(CATALOG_DIR, "..", "..", "frontend", "src", "catalog.gen.ts");

/** The id unions: file -> type name */
const ID_TYPES = {
  items: "ItemId", recipes: "RecipeId", skills: "SkillId", loot: "LootTableId",
  enemies: "EnemyId", regions: "RegionId", npcs: "NpcId", quests: "QuestId",
};

const refName = (ref) => ref.split("/").pop();
const isUnion = (type) => /^[^{[(]*\|/.test(type);
const wrap = (type) => (isUnion(type) ? `(${type})` : type);

function comment(text, indent) {
  return text ? `${indent}/** ${text} */\n` : "";
}

function tsType(schema, indent) {
  if (schema.$ref) return refName(schema.$ref);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      if (schema.prefixItems) return `readonly [${schema.prefixItems.map((item) => tsType(item, indent)).join(", ")}]`;
      return `readonly ${wrap(tsType(schema.items, indent))}[]`;
    case "object": {
      if (schema.properties) return `{\n${fields(schema, `${indent}  `)}${indent}}`;
      const value = tsType(schema.additionalProperties, indent);
      if (schema.propertyNames?.$ref) return `{ readonly [K in ${refName(schema.propertyNames.$ref)}]?: ${value} }`;
      return `{ readonly [key: string]: ${value} }`;
    }
    default:
      throw new Error(`types.mjs: no TypeScript for schema ${JSON.stringify(schema)}`);
  }
}

function fields(schema, indent) {
  const required = new Set(schema.required ?? []);
  let out = "";
  for (const [name, child] of Object.entries(schema.properties)) {
    if (name === "$schema") continue;
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    out += comment(child.description, indent);
    out += `${indent}readonly ${key}${required.has(name) ? "" : "?"}: ${tsType(child, indent)};\n`;
  }
  return out;
}

function declaration(name, schema) {
  const head = comment(schema.description, "");
  if (schema.type === "object" && schema.properties) return `${head}export interface ${name} {\n${fields(schema, "  ")}}\n`;
  return `${head}export type ${name} = ${tsType(schema, "")};\n`;
}

export function generate(dir = CATALOG_DIR) {
  const schemas = loadSchemas(dir);
  const files = loadFiles(dir);
  const seen = new Set();
  const declare = (name, schema) => {
    if (seen.has(name)) throw new Error(`types.mjs: two schema definitions are called ${name}`);
    seen.add(name);
    return declaration(name, schema);
  };
  const parts = [
    "// Generated by shared/catalog/types.mjs from shared/catalog (schemas and ids). Don't edit:\n" +
      "// run `npm run catalog` in frontend/ (npm run build does it too).\n",
  ];
  for (const [name, schema] of Object.entries(schemas["common.schema.json"].$defs)) parts.push(declare(name, schema));
  for (const file of FILES) {
    const schema = schemas[`${file}.schema.json`];
    for (const [name, def] of Object.entries(schema.$defs ?? {})) parts.push(declare(name, def));
    parts.push(declare(schema.title, schema));
  }
  for (const file of FILES) {
    // stats.json's ids are the schema's StatId already
    if (!ID_TYPES[file]) continue;
    const ids = files[file][LISTS[file]].map((entry) => JSON.stringify(entry.id));
    parts.push(`export type ${ID_TYPES[file]} =\n  | ${ids.join("\n  | ")};\n`);
  }
  parts.push(`export type PlaceId = RegionId | ${JSON.stringify(files.regions.hub.id)};\n`);
  return parts.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate();
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    // first run
  }
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error("frontend/src/catalog.gen.ts is stale: run `npm run catalog` in frontend/");
      process.exit(1);
    }
  } else if (current !== text) {
    writeFileSync(OUTPUT, text);
    console.log("wrote frontend/src/catalog.gen.ts");
  }
}
